// Write docs/results/LATEST.md from history.jsonl: the latest nightly run in full, plus recent runs.
// Every number comes from a record that extract-run.mjs read out of a real run's artifacts.
//
//   node scripts/render-results.mjs history.jsonl > docs/results/LATEST.md
import { pathToFileURL } from 'node:url';
import { byDate, readHistory, SERIES, short, day } from './history.mjs';

const RECENT = 10;
const OLD_TASKFLOW = '8b0d564'; // last TaskFlow commit with scryptSync (PERF-001)
const TRENDS_URL = 'https://vincentjerico.github.io/performance-testing/';

const fmt = (v, unit = '') =>
  v === undefined ? 'n/a' : `${v.toLocaleString('en-US')}${unit && ` ${unit}`}`;
const verdict = (g) => (g === 'pass' ? 'pass' : g === 'fail' ? '**FAIL**' : (g ?? 'n/a'));

/** `align`: one 'l' or 'r' per column (default: first column left, the rest right). */
function table(head, rows, align = head.map((_, i) => (i === 0 ? 'l' : 'r'))) {
  return [
    `| ${head.join(' | ')} |`,
    `| ${align.map((a) => (a === 'l' ? '---' : '---:')).join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

export function renderResults(records) {
  const history = byDate(records);
  const r = history.at(-1);
  if (!r) throw new Error('history is empty');
  const out = [
    '# Latest nightly results',
    '',
    `Generated by \`scripts/render-results.mjs\` from the results history. Don't edit by hand.`,
    `Trends over time: [${TRENDS_URL}](${TRENDS_URL}).`,
    '',
    `| Run | Date | Suite commit | TaskFlow |`,
    `| --- | --- | --- | --- |`,
    `| [${r.runId}](${r.runUrl}) | ${day(r.date)} | \`${short(r.commit)}\` | \`${short(r.taskflowRef)}\` |`,
    '',
    '## Gates',
    '',
  ];

  const gateRows = Object.entries(r.authContention ?? {})
    .sort(([a], [b]) => Number(a) - Number(b))
    .map(([rate, a]) => [
      `PERF-001 at ${rate} logins/s`,
      `readers p95 ${fmt(a.duringP95Ms, 'ms')} during logins (baseline ${fmt(a.baselineP95Ms, 'ms')})`,
      `${fmt(a.limitMs, 'ms')}`,
      verdict(a.gate),
    ]);
  if (r.soak) {
    gateRows.push([
      'Soak memory (OBS-002)',
      `second-half slope ${fmt(r.soak.slopeMbPerMin, 'MB/min')}, RSS ${fmt(r.soak.afterWarmupMb)} to ${fmt(r.soak.endMb, 'MB')}`,
      '0.5 MB/min',
      verdict(r.soak.gate),
    ]);
  }
  out.push(
    gateRows.length
      ? table(['Gate', 'Observed', 'Limit', 'Result'], gateRows, ['l', 'l', 'r', 'l'])
      : 'No gate data in this run.',
  );

  const scenarios = ['smoke', 'load', 'stress', 'spike', 'breakpoint'].filter((s) => r[s]);
  out.push(
    '',
    '## Scenarios',
    '',
    table(
      ['Scenario', 'Requests', 'Throughput', 'p95', 'max', 'Failed'],
      scenarios.map((s) => [
        s,
        fmt(r[s].requests),
        fmt(r[s].rps, 'req/s'),
        fmt(r[s].p95Ms, 'ms'),
        fmt(r[s].maxMs, 'ms'),
        `${fmt(r[s].failedRate * 100)}%`,
      ]),
    ),
  );
  if (r.breakpoint?.droppedIterations) {
    out.push(
      '',
      `The breakpoint run dropped ${fmt(r.breakpoint.droppedIterations)} iterations: k6 ran out of VUs.`,
    );
  }

  if (r.listGrowth) {
    out.push(
      '',
      '## List growth',
      '',
      table(
        ['Tasks', 'p95', 'Response size'],
        Object.entries(r.listGrowth).map(([size, v]) => [
          fmt(Number(size)),
          fmt(v.p95Ms, 'ms'),
          fmt(v.bytes, 'bytes'),
        ]),
      ),
    );
  }

  const recent = history.slice(-RECENT).reverse();
  const tracked = SERIES.filter((s) => recent.some((rec) => s.value(rec) !== undefined));
  out.push(
    '',
    `## Last ${recent.length} runs`,
    '',
    table(
      ['Date', 'TaskFlow', ...tracked.map((s) => `${s.title.replace(/^[^:]+: /, '')} (${s.unit})`)],
      recent.map((rec) => [
        `[${day(rec.date)}](${rec.runUrl})`,
        `\`${short(rec.taskflowRef)}\``,
        ...tracked.map((s) => {
          const v = s.value(rec);
          return v === undefined ? '-' : `${fmt(v)}${s.gate?.(rec) === 'fail' ? ' (FAIL)' : ''}`;
        }),
      ]),
      ['l', 'l', ...tracked.map(() => 'r')],
    ),
    '',
    'Runs recorded before the gates were added are judged by the same checks after the fact.',
    ...(recent.some((rec) => rec.taskflowRef?.startsWith(OLD_TASKFLOW))
      ? ['TaskFlow `8b0d564` is the build with PERF-001, so it fails the PERF-001 gate by design.']
      : []),
    '',
  );
  return out.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.stdout.write(renderResults(readHistory(process.argv[2] ?? 'history.jsonl')));
}
